// Config plugin: disable Android auto-backup for SpendFlow (audit run-1 fix).
//
// The Expo template ships android:allowBackup="true" with no exclusion rules,
// which makes the app-private data set — plaintext per-user AsyncStorage
// caches (profile incl. email/budget, expense/account/transfer caches) and
// expo-secure-store chunk files — eligible for cloud backup and
// device-to-device transfer. Those caches are an offline-read convenience
// that repopulates from Supabase on the next sign-in, so the backup channel
// only adds an extraction path that crosses the (client-only) biometric lock.
// android/ is prebuild output regenerated by EAS, so the fix must live in a
// config plugin, not the generated manifest.
const { withAndroidManifest } = require('expo/config-plugins');

module.exports = function withAndroidBackupRules(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (!app) return cfg;
    app.$ = app.$ || {};
    app.$['android:allowBackup'] = 'false';
    // Drop any inherited content-rule attributes so the flag alone governs.
    delete app.$['android:fullBackupContent'];
    delete app.$['android:fullBackupContentAllowlist'];
    delete app.$['android:fullBackupContentDenylist'];
    delete app.$['android:dataExtractionRules'];
    return cfg;
  });
};
